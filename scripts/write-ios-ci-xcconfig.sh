#!/usr/bin/env bash
# Write ios/Config/CI.xcconfig from environment (GitHub Actions or local export).
# xcconfig treats // in URLs as comments — use https:/$()/host/path form.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/ios/Config/CI.xcconfig"

require() {
  local name="$1"
  if [[ -z "${!name:-}" ]]; then
    echo "Missing env: $name" >&2
    exit 1
  fi
}

require IOS_DEVELOPMENT_TEAM
require SUPABASE_URL
require SUPABASE_ANON_KEY
require BIBLE_PROXY_BASE_URL

xcconfig_url() {
  local url="$1"
  if [[ "$url" == https://* ]]; then
    printf 'https:/$()/%s' "${url#https://}"
  elif [[ "$url" == http://* ]]; then
    printf 'http:/$()/%s' "${url#http://}"
  else
    printf '%s' "$url"
  fi
}

mkdir -p "$(dirname "$OUT")"
{
  echo "// Generated by scripts/write-ios-ci-xcconfig.sh — do not commit."
  echo "DEVELOPMENT_TEAM = ${IOS_DEVELOPMENT_TEAM}"
  echo "SUPABASE_URL = $(xcconfig_url "$SUPABASE_URL")"
  echo "SUPABASE_ANON_KEY = ${SUPABASE_ANON_KEY}"
  echo "BIBLE_PROXY_BASE_URL = $(xcconfig_url "$BIBLE_PROXY_BASE_URL")"
  if [[ -n "${SENTRY_DSN:-}" ]]; then
    echo "SENTRY_DSN = $(xcconfig_url "$SENTRY_DSN")"
  fi
} >"$OUT"

echo "Wrote $OUT"
