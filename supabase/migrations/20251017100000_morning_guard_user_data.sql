-- Morning Guard: per-user stats and Bible highlights (PostgREST + RLS)
-- Safe to re-run: uses IF NOT EXISTS / DROP POLICY IF EXISTS where needed.

-- ---------------------------------------------------------------------------
-- morning_day_records (streak / stats sync)
-- ---------------------------------------------------------------------------
create table if not exists public.morning_day_records (
    user_id uuid not null references auth.users (id) on delete cascade,
    date_key date not null,
    outcome text not null,
    recorded_at timestamptz not null default timezone('utc', now()),
    constraint morning_day_records_outcome_check check (
        outcome in ('GOAL_COMPLETED', 'EMERGENCY_BYPASS')
    ),
    constraint morning_day_records_pkey primary key (user_id, date_key)
);

comment on table public.morning_day_records is
    'One row per user per calendar day: goal completed or emergency bypass.';

alter table public.morning_day_records enable row level security;

drop policy if exists "morning_day_records_select_own" on public.morning_day_records;
create policy "morning_day_records_select_own"
    on public.morning_day_records
    for select
    to authenticated
    using (auth.uid() = user_id);

drop policy if exists "morning_day_records_insert_own" on public.morning_day_records;
create policy "morning_day_records_insert_own"
    on public.morning_day_records
    for insert
    to authenticated
    with check (auth.uid() = user_id);

drop policy if exists "morning_day_records_update_own" on public.morning_day_records;
create policy "morning_day_records_update_own"
    on public.morning_day_records
    for update
    to authenticated
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

-- ---------------------------------------------------------------------------
-- bible_highlights (cloud backup / multi-device)
-- ---------------------------------------------------------------------------
create table if not exists public.bible_highlights (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    client_id bigint,
    translation_id text not null,
    book text not null,
    chapter integer not null,
    label text not null default '',
    excerpt text not null,
    selection_start integer,
    selection_end integer,
    created_at timestamptz not null default timezone('utc', now()),
    constraint bible_highlights_chapter_check check (chapter > 0)
);

create index if not exists bible_highlights_user_created_idx
    on public.bible_highlights (user_id, created_at desc);

comment on table public.bible_highlights is
    'User-saved Bible passages; client_id maps to local Room id for sync.';

alter table public.bible_highlights enable row level security;

drop policy if exists "bible_highlights_select_own" on public.bible_highlights;
create policy "bible_highlights_select_own"
    on public.bible_highlights
    for select
    to authenticated
    using (auth.uid() = user_id);

drop policy if exists "bible_highlights_insert_own" on public.bible_highlights;
create policy "bible_highlights_insert_own"
    on public.bible_highlights
    for insert
    to authenticated
    with check (auth.uid() = user_id);

drop policy if exists "bible_highlights_update_own" on public.bible_highlights;
create policy "bible_highlights_update_own"
    on public.bible_highlights
    for update
    to authenticated
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

drop policy if exists "bible_highlights_delete_own" on public.bible_highlights;
create policy "bible_highlights_delete_own"
    on public.bible_highlights
    for delete
    to authenticated
    using (auth.uid() = user_id);

-- ---------------------------------------------------------------------------
-- Privileges: authenticated only (anon has no table grants)
-- ---------------------------------------------------------------------------
revoke all on table public.morning_day_records from anon, public;
revoke all on table public.bible_highlights from anon, public;

grant select, insert, update on table public.morning_day_records to authenticated;
grant select, insert, update, delete on table public.bible_highlights to authenticated;

grant usage on sequence public.bible_highlights_id_seq to authenticated;
